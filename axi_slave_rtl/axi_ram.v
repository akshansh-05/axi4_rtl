// NOTE ON REMOVED ADVANCED SIGNALS:
// The unused AXI4 system signals (AWLOCK, AWCACHE, AWPROT, ARLOCK, ARCACHE, ARPROT)
// have been removed from this module port list to simplify RTL inspection and waveform
